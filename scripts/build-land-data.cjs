// One-off build script: Natural Earth 110m land polygons -> compact TS module.
// Source: https://github.com/nvkelso/natural-earth-vector (public domain)
const fs = require("fs");
const path = require("path");

const TEMP = process.env.TEMP || process.cwd();
const raw = JSON.parse(fs.readFileSync(path.join(TEMP, "land.geojson"), "utf8"));

const rings = [];
for (const feature of raw.features) {
  const geom = feature.geometry;
  if (!geom) continue;
  const polys = geom.type === "Polygon" ? [geom.coordinates] : geom.type === "MultiPolygon" ? geom.coordinates : [];
  for (const poly of polys) {
    for (const ring of poly) {
      const cleaned = [];
      let prevLon = null;
      let prevLat = null;
      let minLon = Infinity;
      let maxLon = -Infinity;
      let minLat = Infinity;
      let maxLat = -Infinity;
      for (const [lon, lat] of ring) {
        const rLon = Math.round(lon * 10) / 10;
        const rLat = Math.round(lat * 10) / 10;
        if (prevLon !== null && Math.abs(rLon - prevLon) < 0.7 && Math.abs(rLat - prevLat) < 0.7) continue;
        cleaned.push(rLon, rLat);
        prevLon = rLon;
        prevLat = rLat;
        if (rLon < minLon) minLon = rLon;
        if (rLon > maxLon) maxLon = rLon;
        if (rLat < minLat) minLat = rLat;
        if (rLat > maxLat) maxLat = rLat;
      }
      if (cleaned.length < 8) continue;
      const spanLon = maxLon - minLon;
      const spanLat = maxLat - minLat;
      const area = spanLon * spanLat;
      if (area < 1.2) continue;
      rings.push(cleaned);
    }
  }
}

rings.sort((a, b) => b.length - a.length);

const header = `/* Simplified land outlines for the SWARMNET globe.
 * Source: Natural Earth 1:110m land (public domain), rounded to 0.1 degrees.
 * Coordinates are [lon, lat, lon, lat, ...] rings. Schematic display only.
 * Generated by scripts/build-land-data.cjs from ne_110m_land.geojson. */
`;
const body = `export const LAND_RINGS: readonly (readonly number[])[] = [\n${rings
  .map((ring) => `  [${ring.join(",")}]`)
  .join(",\n")}\n];\n`;

const outPath = path.resolve(process.argv[2]);
fs.writeFileSync(outPath, header + body, "utf8");
console.log(`rings=${rings.length} bytes=${Buffer.byteLength(header + body)} -> ${outPath}`);